package com.xavierclavel.dtos.sync

import com.xavierclavel.enums.ExpenseType
import com.xavierclavel.enums.SyncEntityType
import com.xavierclavel.utils.BigDecimalSerializer
import com.xavierclavel.utils.LocalDateSerializer
import com.xavierclavel.utils.UUIDSerializer
import kotlinx.serialization.Serializable
import java.math.BigDecimal
import java.time.LocalDate
import java.util.UUID

/**
 * A set of changes to a user's data: rows to create or update, and rows to delete. A device
 * sends its local changes in this shape (`POST /sync/push`) and receives the server's in it
 * (`GET /sync/pull`). Rows are identified by UUIDs, generated by whoever creates the row.
 *
 * Pulled rows also carry their `serverId`, the id the REST API knows them by, for the features
 * that still go through it. The server ignores it in pushes.
 */
@Serializable
data class SyncChanges(
    val categories: List<SyncCategory> = emptyList(),
    val subcategories: List<SyncSubcategory> = emptyList(),
    val tags: List<SyncTag> = emptyList(),
    val expenses: List<SyncExpense> = emptyList(),
    val recurringExpenses: List<SyncRecurringExpense> = emptyList(),
    val deletions: List<SyncDeletion> = emptyList(),
)

/**
 * @property type Immutable: a change sent for an existing category is ignored.
 */
@Serializable
data class SyncCategory(
    @Serializable(with = UUIDSerializer::class)
    val id: UUID,
    val serverId: Long? = null,
    val name: String,
    val color: String,
    val icon: String,
    val type: ExpenseType,
)

/**
 * Subcategory as stored. A default subcategory is displayed with its parent's icon and name;
 * every subcategory is displayed with its parent's color.
 *
 * @property type Immutable: a change sent for an existing subcategory is ignored.
 * @property isDefault Immutable. A new category needs exactly one default subcategory: send it
 * in the same push as its category, or the server creates one.
 */
@Serializable
data class SyncSubcategory(
    @Serializable(with = UUIDSerializer::class)
    val id: UUID,
    val serverId: Long? = null,
    @Serializable(with = UUIDSerializer::class)
    val categoryId: UUID,
    val name: String,
    val icon: String,
    val type: ExpenseType,
    val isDefault: Boolean,
)

@Serializable
data class SyncTag(
    @Serializable(with = UUIDSerializer::class)
    val id: UUID,
    val serverId: Long? = null,
    val label: String,
)

/**
 * @property subcategoryId The expense's subcategory, or null when uncategorized.
 * @property type Immutable: a change sent for an existing expense is ignored.
 */
@Serializable
data class SyncExpense(
    @Serializable(with = UUIDSerializer::class)
    val id: UUID,
    val serverId: Long? = null,
    @Serializable(with = UUIDSerializer::class)
    val subcategoryId: UUID?,
    val title: String,
    @Serializable(with = BigDecimalSerializer::class)
    val amount: BigDecimal,
    val currency: String,
    @Serializable(with = LocalDateSerializer::class)
    val date: LocalDate,
    val type: ExpenseType,
    val tagIds: List<@Serializable(with = UUIDSerializer::class) UUID> = emptyList(),
)

/**
 * A template the server creates an expense from every month, on [dayOfMonth] (the last day of
 * shorter months). The expenses it creates are synced like any other.
 *
 * @property nextDate The date of the next expense it creates. Set by the server, except in the
 * push creating it: the first occurrence as the device computed it, possibly offline days before,
 * so that it isn't skipped. When missing, the server computes it from today.
 * @property lastGeneratedDate The date of the last expense it created. Set by the server, except
 * in the push creating it from an expense: that expense's date, which then counts as its month's
 * occurrence.
 */
@Serializable
data class SyncRecurringExpense(
    @Serializable(with = UUIDSerializer::class)
    val id: UUID,
    val serverId: Long? = null,
    @Serializable(with = UUIDSerializer::class)
    val subcategoryId: UUID?,
    val title: String,
    @Serializable(with = BigDecimalSerializer::class)
    val amount: BigDecimal,
    val currency: String,
    val type: ExpenseType,
    val tagIds: List<@Serializable(with = UUIDSerializer::class) UUID> = emptyList(),
    val dayOfMonth: Int,
    @Serializable(with = LocalDateSerializer::class)
    val nextDate: LocalDate? = null,
    @Serializable(with = LocalDateSerializer::class)
    val lastGeneratedDate: LocalDate? = null,
)

@Serializable
data class SyncDeletion(
    val type: SyncEntityType,
    @Serializable(with = UUIDSerializer::class)
    val id: UUID,
)
